package kz.clientflow.payment;

import java.math.BigDecimal;
import java.time.Instant;
import java.time.LocalDate;
import java.util.UUID;

import org.hibernate.annotations.CreationTimestamp;

import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.EnumType;
import jakarta.persistence.Enumerated;
import jakarta.persistence.FetchType;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.JoinColumn;
import jakarta.persistence.ManyToOne;
import jakarta.persistence.Table;
import kz.clientflow.user.User;

/**
 * A payment for an order. Payments are never edited or deleted: a wrong payment
 * is voided (with a reason) and a new one is recorded, so the full financial
 * history is preserved.
 */
@Entity
@Table(name = "payments")
public class Payment {

    public enum Method {
        CASH, CARD, BANK_TRANSFER, OTHER
    }

    @Id
    @GeneratedValue(strategy = GenerationType.UUID)
    private UUID id;

    @Column(nullable = false, updatable = false)
    private UUID workspaceId;

    @Column(nullable = false, updatable = false)
    private UUID orderId;

    @Column(nullable = false, precision = 14, scale = 2, updatable = false)
    private BigDecimal amount;

    @Enumerated(EnumType.STRING)
    @Column(nullable = false, length = 15, updatable = false)
    private Method paymentMethod;

    @Column(nullable = false, updatable = false)
    private LocalDate paymentDate;

    @Column(length = 100, updatable = false)
    private String reference;

    /** Generated by the client once per submission; a repeated request returns the same payment. */
    @Column(nullable = false, updatable = false)
    private UUID idempotencyKey;

    @ManyToOne(fetch = FetchType.LAZY)
    @JoinColumn(name = "created_by", updatable = false)
    private User createdBy;

    @CreationTimestamp
    @Column(nullable = false, updatable = false)
    private Instant createdAt;

    private Instant voidedAt;

    @ManyToOne(fetch = FetchType.LAZY)
    @JoinColumn(name = "voided_by")
    private User voidedBy;

    @Column(length = 300)
    private String voidReason;

    protected Payment() {
    }

    public Payment(UUID workspaceId, UUID orderId, BigDecimal amount, Method paymentMethod, LocalDate paymentDate,
                   String reference, UUID idempotencyKey, User createdBy) {
        this.workspaceId = workspaceId;
        this.orderId = orderId;
        this.amount = amount;
        this.paymentMethod = paymentMethod;
        this.paymentDate = paymentDate;
        this.reference = reference;
        this.idempotencyKey = idempotencyKey;
        this.createdBy = createdBy;
    }

    public UUID getId() {
        return id;
    }

    public UUID getOrderId() {
        return orderId;
    }

    public BigDecimal getAmount() {
        return amount;
    }

    public Method getPaymentMethod() {
        return paymentMethod;
    }

    public LocalDate getPaymentDate() {
        return paymentDate;
    }

    public String getReference() {
        return reference;
    }

    public User getCreatedBy() {
        return createdBy;
    }

    public Instant getCreatedAt() {
        return createdAt;
    }

    public boolean isVoided() {
        return voidedAt != null;
    }

    public Instant getVoidedAt() {
        return voidedAt;
    }

    public User getVoidedBy() {
        return voidedBy;
    }

    public String getVoidReason() {
        return voidReason;
    }

    public void voidPayment(User by, String reason, Instant now) {
        this.voidedAt = now;
        this.voidedBy = by;
        this.voidReason = reason;
    }
}
